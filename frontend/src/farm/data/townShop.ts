import type { ObjectDef, ObjectLook } from '../types'

/** The bigger shop: more city buildings, food workshops and decorations. Sorted by level in the shop itself. */

const one = () => 1

function city(def: Pick<ObjectDef, 'id' | 'name' | 'icon' | 'cost' | 'requiredLevel' | 'buildTime' | 'xpReward' | 'look'> & Partial<ObjectDef>): ObjectDef {
  return {
    kind: 'city',
    shopCategory: 'buildings',
    width: 2,
    height: 2,
    productionSlots: 0,
    recipes: [],
    maxCount: (level) => Math.min(10, 1 + Math.ceil(level / 2)),
    ...def,
  }
}

function workshop(def: Pick<ObjectDef, 'id' | 'name' | 'icon' | 'cost' | 'requiredLevel' | 'buildTime' | 'xpReward' | 'recipes' | 'look'>): ObjectDef {
  return {
    kind: 'production',
    shopCategory: 'production',
    width: 2,
    height: 2,
    productionSlots: 3,
    maxCount: one,
    ...def,
  }
}

const many = () => 99

function deco(id: string, name: ObjectDef['name'], icon: string, cost: number, requiredLevel: number, look: ObjectLook, size = 1): ObjectDef {
  return {
    id,
    name,
    icon,
    kind: 'decoration',
    shopCategory: 'decorations',
    cost,
    requiredLevel,
    width: size,
    height: size,
    buildTime: 0,
    productionSlots: 0,
    recipes: [],
    xpReward: 1,
    maxCount: many,
    look,
  }
}

